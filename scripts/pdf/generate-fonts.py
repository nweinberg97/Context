"""
Generates src/lib/pdf/fonts.generated.ts from the Archivo variable fonts.

  python3 scripts/pdf/generate-fonts.py path/to/Archivo[wdth,wght].ttf path/to/Archivo-Italic[wdth,wght].ttf

Each style is a static instance of the variable font, subset to the Windows-1252
(WinAnsi) character set the PDF writer encodes, then embedded as base64 alongside the
metrics the layout engine needs (advance widths per WinAnsi code, ascent, descent...).
Archivo is licensed under the SIL Open Font License 1.1 (public/fonts/OFL-archivo.txt).
"""
import base64, io, json, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

roman_path, italic_path = sys.argv[1], sys.argv[2]
STYLES = {
    "regular": (roman_path, {"wght": 400, "wdth": 100}),
    "semibold": (roman_path, {"wght": 600, "wdth": 100}),
    "display": (roman_path, {"wght": 720, "wdth": 125}),
    "label": (roman_path, {"wght": 600, "wdth": 125}),
    "italic": (italic_path, {"wght": 400, "wdth": 100}),
}

# Windows-1252 code points 32-255 (undefined slots map to None).
winansi = {}
for code in range(32, 256):
    try:
        winansi[code] = ord(bytes([code]).decode("cp1252"))
    except UnicodeDecodeError:
        winansi[code] = None
unicodes = sorted({u for u in winansi.values() if u is not None})

out = {}
for name, (path, axes) in STYLES.items():
    font = instancer.instantiateVariableFont(TTFont(path), axes)
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.recalc_bounds = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    # Drop tables PDF viewers don't need.
    for tag in ("GSUB", "GPOS", "GDEF", "STAT", "fvar", "gvar", "avar", "HVAR", "MVAR", "DSIG"):
        if tag in font:
            del font[tag]
    buf = io.BytesIO()
    font.save(buf)
    data = buf.getvalue()

    upm = font["head"].unitsPerEm
    scale = 1000 / upm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"].metrics
    widths = []
    for code in range(32, 256):
        u = winansi[code]
        g = cmap.get(u) if u is not None else None
        widths.append(round(hmtx[g][0] * scale) if g else round(hmtx[".notdef"][0] * scale))
    os2 = font["OS/2"]
    head = font["head"]
    ps_name = f"Archivo-{name.capitalize()}"
    out[name] = {
        "postScriptName": ps_name,
        "ascent": round(os2.sTypoAscender * scale),
        "descent": round(os2.sTypoDescender * scale),
        "capHeight": round(getattr(os2, "sCapHeight", 700) * scale),
        "bbox": [round(v * scale) for v in (head.xMin, head.yMin, head.xMax, head.yMax)],
        "italicAngle": -12 if name == "italic" else 0,
        "stemV": 120 if name in ("display", "semibold", "label") else 80,
        "widths": widths,
        "data": base64.b64encode(data).decode(),
    }
    print(f"{name}: {len(data) // 1024} KB", file=sys.stderr)

ts = (
    "/* eslint-disable */\n"
    "// Generated by scripts/pdf/generate-fonts.py. Do not edit by hand.\n"
    "// Archivo, SIL Open Font License 1.1 (see public/fonts/OFL-archivo.txt).\n\n"
    "export interface PdfFontData {\n  postScriptName: string;\n  ascent: number;\n  descent: number;\n  capHeight: number;\n"
    "  bbox: [number, number, number, number];\n  italicAngle: number;\n  stemV: number;\n"
    "  /** Advance widths (1000 units/em) for WinAnsi codes 32-255. */\n  widths: number[];\n  /** Base64 TrueType file. */\n  data: string;\n}\n\n"
    f"export const PDF_FONTS = {json.dumps(out)} as const satisfies Record<string, PdfFontData>;\n"
)
open("src/lib/pdf/fonts.generated.ts", "w").write(ts)
